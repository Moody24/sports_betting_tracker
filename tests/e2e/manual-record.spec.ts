import AxeBuilder from '@axe-core/playwright';
import { expect, test } from '@playwright/test';
import { registerAndLogin } from './helpers/auth';
import { labelFixture } from './helpers/fixture-label';

test('manual record works without feeds, retains its price, and supports ledger controls', async ({ page }, testInfo) => {
  await registerAndLogin(page);
  await page.route('**/nba/upcoming-games', route => route.fulfill({ json: [] }));
  await page.route('**/nba/all-props*', route => route.fulfill({ json: [] }));
  await page.goto('/bets/new');
  await labelFixture(page);
  await expect(page.locator('#ub-game-picker')).toBeDisabled();
  const manual = page.locator('#ub-manual-form');
  if (!(await manual.isVisible())) await page.getByText('Record a bet manually', { exact: true }).click();
  await page.locator('#ub-manual-away').fill('Preview Away');
  await page.locator('#ub-manual-home').fill('Preview Home');
  await page.locator('#ub-manual-date').fill('2026-10-20');
  await page.locator('#ub-manual-market').selectOption('moneyline');
  await page.locator('#ub-manual-side').selectOption('home');
  await page.locator('#ub-manual-odds').fill('135');
  await manual.getByRole('button', { name: 'Add selection' }).click();
  await expect(page.locator('#ub-slip-list')).toContainText('Preview Home ML');
  await page.screenshot({ path: testInfo.outputPath('manual-builder.png'), fullPage: true });
  const accessibility = await new AxeBuilder({ page }).analyze();
  expect(accessibility.violations.filter(item => ['serious', 'critical'].includes(item.impact || ''))).toEqual([]);
  await page.locator('#ub-refresh-btn').click();
  await expect(page.locator('#ub-slip-list input[type="number"]').last()).toHaveValue('135');
  await page.locator('#ub-stake').fill('20');
  await page.locator('#ub-submit-btn').click();
  await expect(page).toHaveURL(/\/bets$/);
  await labelFixture(page);
  await expect(page.locator('[data-testid="bets-list"]')).toContainText('Preview Away');
  await page.locator('#filter-q').fill('Preview Home');
  await page.getByRole('button', { name: 'Apply filters' }).click();
  await labelFixture(page);
  await expect(page.locator('[data-testid="bets-list"] .row-line')).toHaveCount(1);
  const row = page.locator('[data-testid="bets-list"] .row-line').first();
  await row.getByRole('button', { name: 'Grade', exact: true }).click();
  await row.getByRole('button', { name: 'Win', exact: true }).click();
  await labelFixture(page);
  await expect(page.locator('[data-testid="bets-list"]')).toContainText('+$27.00');
  for (const close of await page.locator('.toast-close').all()) await close.click();
  await expect(page.locator('.toast-item')).toHaveCount(0);
  await page.screenshot({ path: testInfo.outputPath('manual-ledger.png'), fullPage: true });
  await page.goto('/dashboard');
  await labelFixture(page);
  await page.screenshot({ path: testInfo.outputPath('desktop-overview.png'), fullPage: true });
  await page.goto('/bets');
  await labelFixture(page);
  const download = page.waitForEvent('download');
  await page.getByRole('link', { name: 'Export CSV', exact: true }).click();
  expect((await download).suggestedFilename()).toMatch(/\.csv$/);
  page.on('dialog', dialog => dialog.accept());
  await page.locator('.delete-bet-form button').first().click();
  await expect(page.locator('[data-testid="bets-list"]')).not.toContainText('Preview Away');
});

test('manual props require their player, line and recorded price', async ({ page }) => {
  await registerAndLogin(page);
  await page.route('**/nba/upcoming-games', route => route.fulfill({ json: [] }));
  await page.goto('/bets/new');
  await labelFixture(page);
  const form = page.locator('#ub-manual-form');
  if (!(await form.isVisible())) await page.getByText('Record a bet manually', { exact: true }).click();
  await page.locator('#ub-manual-away').fill('Preview Away');
  await page.locator('#ub-manual-home').fill('Preview Home');
  await page.locator('#ub-manual-date').fill('2026-10-20');
  await page.locator('#ub-manual-market').selectOption('player_points');
  await expect(page.locator('#ub-manual-player')).toBeVisible();
  await expect(page.locator('#ub-manual-line')).toBeVisible();
  await page.locator('#ub-manual-side').selectOption('under');
  await page.locator('#ub-manual-player').fill('Preview Player');
  await page.locator('#ub-manual-line').fill('24.5');
  await page.locator('#ub-manual-odds').fill('-115');
  await form.getByRole('button', { name: 'Add selection' }).click();
  await expect(page.locator('#ub-slip-list')).toContainText('Preview Player');
  await expect(page.locator('#ub-slip-list')).toContainText('UNDER 24.5');
  await page.locator('#ub-stake').fill('10');
  await page.locator('#ub-submit-btn').click();
  await expect(page).toHaveURL(/\/bets$/);
  await expect(page.locator('[data-testid="bets-list"]')).toContainText('Preview Player');
  await expect(page.locator('[data-testid="bets-list"]')).toContainText('-115');
});
